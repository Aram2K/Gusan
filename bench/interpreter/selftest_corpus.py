def check_scripts(text, lang, langs, where, rep):
    present = scripts_in(text)
    own = SCRIPTS.get(lang, set())
    if own and not present & own:
        rep.err(f"{where}: no {'/'.join(sorted(own))} letters in a '{lang}' line")
    for s in sorted(present - own):
        if not any(s in SCRIPTS.get(other, ()) for other in langs if other != lang):
            rep.err(f"{where}: {s} letters in a '{lang}' line, but langs {langs} names no {s} language")


def check_ref_script(text, lang, where, rep):
    present = scripts_in(text)
    own = SCRIPTS.get(lang, set())
    if own and not present & own:
        rep.err(f"{where}: the '{lang}' reference has no {'/'.join(sorted(own))} letters")
    if own == {"Latin"} and present - own:
        rep.err(f"{where}: the '{lang}' reference has {'/'.join(sorted(present - own))} letters")


_HY_MARK_AFTER_DIGRAPH = re.compile("ու[՛՜՞]")     # ՛ ՜ ՞ written after "ու"


def check_armenian(text, where, rep):
    """Armenian stress, exclamation and question marks sit on the stressed vowel; for the digraph
    "ու" they go on its "ո" (ո՞ւր, ինչո՞ւ), never after it."""
    m = _HY_MARK_AFTER_DIGRAPH.search(text)
    if m:
        rep.err(f"{where}: '{m.group()}' should be '{m.group()[0]}{m.group()[2]}{m.group()[1]}'")


def check_conversation(path, voices, rep):
    """Checks one file -> a summary dict (None when it cannot be read at all)."""
    name = path.name
    try:
        c = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        rep.err(f"{name}: cannot read ({e})")
        return None
    if not isinstance(c, dict):
        rep.err(f"{name}: must be a JSON object")
        return None
    missing = [k for k in CONV_KEYS if k not in c]
    extra = [k for k in c if k not in CONV_KEYS]
    if missing:
        rep.err(f"{name}: missing keys {missing}")
        return None
    if extra:
        rep.err(f"{name}: keys outside the schema {extra}")

    cid, my, their, me = c["id"], c["my_lang"], c["their_lang"], c["me"]
    if not all(isinstance(x, str) for x in (cid, my, their, me)):
        rep.err(f"{name}: id, me, my_lang and their_lang must be strings")
        return None
    if cid != path.stem:
        rep.err(f"{name}: id '{cid}' does not match the file name")
    m = ID_RE.match(str(cid))
    if not m:
        rep.err(f"{name}: id must look like c01_en_hy_standup")
    elif (m.group(2), m.group(3)) != (my, their):
        rep.err(f"{name}: id says {m.group(2)}/{m.group(3)} but my_lang/their_lang are {my}/{their}")
    for k in ("title", "scenario"):
        if not isinstance(c[k], str) or not c[k].strip():
            rep.err(f"{name}: {k} must be a non-empty string")
    for k in ("tags", "glossary"):
        if not isinstance(c[k], list) or not all(isinstance(x, str) and x.strip() for x in c[k]):
            rep.err(f"{name}: {k} must be a list of non-empty strings")
            c[k] = [x for x in c[k] if isinstance(x, str)] if isinstance(c[k], list) else []
        if len(set(c[k])) != len(c[k]):
            rep.err(f"{name}: duplicate {k} entries")
    for k in ("my_lang", "their_lang"):
        if c[k] not in LANG_CODES:
            rep.err(f"{name}: {k} '{c[k]}' is not an interpreter language")
    if my == their:
        rep.err(f"{name}: my_lang and their_lang are the same")

    # speakers
    speakers = c["speakers"] if isinstance(c["speakers"], dict) else {}
    if not speakers:
        rep.err(f"{name}: speakers must be a non-empty object")
    if me not in speakers:
        rep.err(f"{name}: me '{me}' is not a speaker")
    used_voices = {}
    for sid, sp in speakers.items():
        where = f"{name}: speaker '{sid}'"
        if not SPEAKER_ID_RE.match(sid):
            rep.err(f"{where}: ids are lower case (letters, digits, _)")
        if not isinstance(sp, dict) or sorted(sp) != sorted(SPEAKER_KEYS):
            rep.err(f"{where}: needs exactly the keys {list(SPEAKER_KEYS)}")
            continue
        if not all(isinstance(sp[k], str) and sp[k].strip() for k in SPEAKER_KEYS):
            rep.err(f"{where}: every field must be a non-empty string")
            continue
        if sp["gender"] not in ("male", "female"):
            rep.err(f"{where}: gender must be male or female (the hear voice is matched on it)")
        v = voices.get(sp["voice"])
        if not v:
            rep.err(f"{where}: voice {sp['voice']} is not in voices.json")
        elif v["gender"] != sp["gender"]:
            rep.err(f"{where}: is {sp['gender']} but voice {v['name']} is {v['gender']}")
        if sp["voice"] in used_voices:
            rep.err(f"{where}: shares voice {sp['voice']} with '{used_voices[sp['voice']]}'")
        used_voices[sp["voice"]] = sid
        if sp["voice"] in HEAR_DEFAULTS:
            rep.warn(f"{where}: uses {HEAR_DEFAULTS[sp['voice']]}, one of the app's hear voices "
                     "(the corpus voice would sound like Gusan's own output)")
    others = {sid: sp for sid, sp in speakers.items() if sid != me and isinstance(sp, dict)}
    if not others:
        rep.err(f"{name}: needs at least one speaker besides me")
    far_genders = Counter(sp.get("gender") for sp in others.values())

    # turns
    turns = c["turns"] if isinstance(c["turns"], list) else []
    if not turns:
        rep.err(f"{name}: turns must be a non-empty list")
    s = {
        "id": cid, "path": path, "my": my, "their": their, "me": me, "tags": list(c["tags"]),
        "speakers": speakers, "far_genders": far_genders, "glossary": list(c["glossary"]),
        "turns": len(turns), "chars": 0, "speech": 0.0, "duration": 0.0, "mixed": 0, "overlaps": [],
        "pauses": 0, "longest": (0.0, ""), "note_tags": Counter(), "ref_chars": Counter(),
        "chars_by_lang": Counter(), "shortest": [], "texts": [], "refs": [], "monologue": [],
    }
    prev_end = 0.0
    for i, t in enumerate(turns):
        where = f"{name} turn {i + 1}"
        if not isinstance(t, dict):
            rep.err(f"{where}: must be an object")
            continue
        missing = [k for k in TURN_KEYS if k not in t]
        extra = [k for k in t if k not in TURN_KEYS]
        if missing:
            rep.err(f"{where}: missing keys {missing}")
            continue
        if extra:
            rep.err(f"{where}: keys outside the schema {extra}")
        spk, lang, text, langs, ref, gap, notes = (t[k] for k in TURN_KEYS)
        if not isinstance(spk, str) or spk not in speakers:
            rep.err(f"{where}: unknown speaker '{spk}'")
            continue
        mine = spk == me
        want_lang, target = (my, their) if mine else (their, my)
        if lang != want_lang:
            rep.err(f"{where}: lang '{lang}' but {'my' if mine else 'their'} side speaks '{want_lang}'")
        if not isinstance(text, str) or not text.strip():
            rep.err(f"{where}: text must be a non-empty string")
            continue
        if text != text.strip() or "\n" in text or "  " in text:
            rep.err(f"{where}: text has stray spaces or a line break")
        if len(text) > MAX_TTS_CHARS:
            rep.err(f"{where}: {len(text)} characters (one tts call takes at most {MAX_TTS_CHARS})")
        if (not isinstance(langs, list) or not langs or len(set(langs)) != len(langs)
                or any(x not in LANG_CODES for x in langs)):
            rep.err(f"{where}: langs must be a list of distinct interpreter language codes")
            langs = [lang]
        if langs[0] != lang:
            rep.err(f"{where}: langs must start with lang '{lang}' (the line's main language)")
        check_scripts(text, lang, langs, where, rep)
        if "hy" in langs:
            check_armenian(text, where, rep)

        # references
        if not isinstance(ref, dict) or not ref:
            rep.err(f"{where}: ref must be a non-empty object")
            ref = {}
        for k, v in ref.items():
            if k not in LANG_CODES or not isinstance(v, str) or not v.strip():
                rep.err(f"{where}: ref '{k}' must be an interpreter language with a non-empty text")
                continue
            check_ref_script(v, k, f"{where} ref.{k}", rep)
            if k == "hy":
                check_armenian(v, f"{where} ref.hy", rep)
        if target not in ref:
            rep.err(f"{where}: {'my' if mine else 'their'} turn needs ref['{target}']")
        if "en" not in ref:
            rep.err(f"{where}: needs ref['en'] (English always)")
        extra_refs = set(ref) - {target, "en"}
        if extra_refs:
            rep.warn(f"{where}: extra references {sorted(extra_refs)}")
        if target != lang and ref.get(target) == text:
            rep.err(f"{where}: ref['{target}'] is a copy of the text")
        if lang == "en" and langs == ["en"] and "en" in ref and ref["en"] != text:
            rep.err(f"{where}: an English line's ref['en'] must be the line itself")
        if target in ref:
            s["ref_chars"]["me" if mine else "them"] += len(ref[target])
        s["refs"].extend(v for v in ref.values() if isinstance(v, str))

        # timing
        if isinstance(gap, bool) or not isinstance(gap, (int, float)):
            rep.err(f"{where}: gap_before must be a number")
            gap = 0.0
        if not GAP_MIN <= gap <= GAP_MAX:
            rep.err(f"{where}: gap_before {gap} is outside [{GAP_MIN}, {GAP_MAX}]")
        if i == 0 and gap < 0:
            rep.err(f"{where}: the first turn cannot overlap anything")
        dur = est_seconds(text, lang)
        start = prev_end + gap
        prev_end = start + dur
        s["duration"] = max(s["duration"], prev_end)
        s["speech"] += dur
        s["chars"] += len(text)
        s["chars_by_lang"][lang] += len(text)
        s["texts"].append(text)
        if gap < 0:
            s["overlaps"].append(gap)
        if gap >= 2.0:
            s["pauses"] += 1
        if len(langs) > 1:
            s["mixed"] += 1
        if dur > s["longest"][0]:
            who = speakers.get(spk)
            s["longest"] = (dur, who.get("name", spk) if isinstance(who, dict) else spk)
        if len(text) <= 6:
            s["shortest"].append(text)

        # notes and their #tags
        if not isinstance(notes, str):
            rep.err(f"{where}: notes must be a string")
            notes = ""
        tags = note_tags(notes)
        unknown = [x for x in tags if x not in NOTE_TAGS]
        if unknown:
            rep.err(f"{where}: unknown #tags {unknown} (allowed: {', '.join(sorted(NOTE_TAGS))})")
        s["note_tags"].update(set(tags))
        if ("overlap" in tags) != (gap < 0):
            rep.err(f"{where}: #overlap must mark exactly the turns with a negative gap_before")
        if ("pause" in tags) != (gap >= 2.0):
            rep.err(f"{where}: #pause must mark exactly the turns with gap_before >= 2 s")
        if ("mixed" in tags) != (len(langs) > 1):
            rep.err(f"{where}: #mixed must mark exactly the lines with more than one language in langs")
        if "monologue" in tags:
            s["monologue"].append(dur)
            if not MONOLOGUE_RANGE[0] <= dur <= MONOLOGUE_RANGE[1]:
                rep.err(f"{where}: #monologue is about {dur:.0f} s (estimate), not {MONOLOGUE_RANGE[0]:.0f}-"
                        f"{MONOLOGUE_RANGE[1]:.0f} s")
        if "long" in tags and dur < LONG_MIN_S:
            rep.warn(f"{where}: #long but only about {dur:.0f} s")
        if "short" in tags and dur > SHORT_MAX_S:
            rep.warn(f"{where}: #short but about {dur:.1f} s")

    # conversation tags that follow from the data
    tags = set(c["tags"])
    derived = {
        "1-to-1": len(speakers) == 2,
        "3-person": len(speakers) == 3,
        "man-and-woman": far_genders["male"] > 0 and far_genders["female"] > 0,
        "two-women": far_genders["female"] >= 2 and far_genders["male"] == 0,
        "overlap": bool(s["overlaps"]),
        "pause": s["pauses"] > 0,
        "mixed": s["mixed"] > 0,
    }
    derived.update({tag: s["note_tags"][nt] > 0 for tag, nt in DERIVED_FROM_NOTES.items()})
    for tag, truth in derived.items():
        if truth and tag not in tags:
            rep.err(f"{name}: add the tag '{tag}' (the turns have it)")
        elif tag in tags and not truth:
            rep.err(f"{name}: the tag '{tag}' is not true of the turns")
    for tag in sorted(tags - set(derived) - FREE_TAGS):
        rep.warn(f"{name}: tag '{tag}' is not in the documented tag list")

    if not SPEECH_RANGE[0] <= s["speech"] <= SPEECH_RANGE[1]:
        rep.warn(f"{name}: about {s['speech']:.0f} s of speech (aim {SPEECH_RANGE[0]:.0f}-{SPEECH_RANGE[1]:.0f} s)")
    haystack = " ".join(s["texts"] + s["refs"]).lower()
    for term in s["glossary"]:
        if term.lower() not in haystack:
            rep.warn(f"{name}: glossary term '{term}' never occurs in the conversation")
    return s


# ---------------------------------------------------------------- corpus-level coverage

def check_coverage(convs, rep):
    total = sum(c["chars"] for c in convs)
    if total > MAX_CHARS:
        rep.err(f"corpus: {fmt_int(total)} characters of spoken text, over the {fmt_int(MAX_CHARS)} limit")
    ids = Counter(c["id"] for c in convs)
    for cid, n in ids.items():
        if n > 1:
            rep.err(f"corpus: id {cid} is used {n} times")
    if len(convs) < 8:
        rep.warn(f"corpus: only {len(convs)} conversations (about 10 planned)")

    pairs = Counter(frozenset((c["my"], c["their"])) for c in convs)
    for a, b in (("en", "hy"), ("en", "ru"), ("hy", "ru"), ("en", "fr"), ("en", "es"), ("en", "ar"),
                 ("en", "ja"), ("en", "zh")):
        if not pairs[frozenset((a, b))]:
            rep.err(f"corpus: no {a}<->{b} conversation")
    if pairs[frozenset(("en", "hy"))] < 2:
        rep.err("corpus: needs at least 2 en<->hy conversations (the founder's main case)")
    if not any(c["my"] == "hy" and c["their"] == "en" for c in convs):
        rep.err("corpus: needs an en<->hy conversation where me speaks Armenian")
    if not (pairs[frozenset(("en", "ka"))] or pairs[frozenset(("en", "de"))]):
        rep.err("corpus: needs an en<->ka or en<->de conversation")

    mixed = sum(c["mixed"] for c in convs)
    if mixed < MIN_MIXED_LINES:
        rep.err(f"corpus: {mixed} mixed-language lines (need {MIN_MIXED_LINES})")
    if not any(c["far_genders"]["male"] and c["far_genders"]["female"] and len(c["speakers"]) >= 3 for c in convs):
        rep.err("corpus: needs a 3-person meeting with a man and a woman on the far side")
    if not any(c["far_genders"]["female"] >= 2 and not c["far_genders"]["male"] for c in convs):
        rep.err("corpus: needs a conversation where the far side is two women")
    me_genders = {c["speakers"][c["me"]].get("gender") for c in convs if isinstance(c["speakers"].get(c["me"]), dict)}
    if not {"male", "female"} <= me_genders:
        rep.warn("corpus: 'me' is always the same gender")
    for tag in VARIANT_TAGS + ("formal", "casual"):
        if not any(tag in c["tags"] for c in convs):
            rep.err(f"corpus: no conversation tagged '{tag}'")
    if sum("speakers" in c["tags"] for c in convs) != 1:
        rep.warn("corpus: the plan has exactly one 'speakers' conversation")

    gaps = [g for c in convs for g in c["overlaps"]]
    if not gaps or min(gaps) > -0.3:
        rep.err("corpus: needs fast back-and-forth with overlaps of at least 0.3 s")
    if not any(c["pauses"] for c in convs):
        rep.err("corpus: needs a long pause (gap_before >= 2.5 s)")
    if not any(MONOLOGUE_RANGE[0] <= d <= MONOLOGUE_RANGE[1] for c in convs for d in c["monologue"]):
        rep.err("corpus: needs a #monologue of 25-35 s")
    shorts = [t for c in convs for t in c["shortest"]]
    if len(shorts) < 5:
        rep.err(f"corpus: only {len(shorts)} very short replies (<= 6 characters)")
    texts = " ".join(t for c in convs for t in c["texts"])
    for term in ("Gusan", "Supabase", "ElevenLabs", "Zoom"):
        if term not in texts:
            rep.err(f"corpus: nobody says '{term}'")
    for tag, need in (("question", 10), ("filler", 5), ("money", 1), ("date", 1), ("time", 1), ("email", 2),
                      ("url", 1), ("spelled", 1), ("numbers", 1), ("names", 1), ("gender", 1)):
        have = sum(c["note_tags"][tag] for c in convs)      # turns carrying the #tag
        if have < need:
            rep.err(f"corpus: {have} turns with #{tag} (need {need})")


# ---------------------------------------------------------------- DESIGN.md table

NUMBER_KINDS = ("numbers", "money", "date", "time", "email", "url", "spelled")


def table(convs):
    def spk(c):
        out = []
        for sid, sp in c["speakers"].items():
            if not isinstance(sp, dict):
                continue
            g = {"male": "m", "female": "f"}.get(sp.get("gender"), "?")
            mark = "*" if sid == c["me"] else ""
            out.append(f"{sp.get('name', sid)}{mark} {g}")
        return " · ".join(out)

    lines = [
        "| conversation | pair (mine ⇄ theirs) | speakers (* = me) | mixed lines | numbers & co. | overlaps"
        " | longest turn | variants | seconds, est. (speech) | chars |",
        "|---|---|---|---:|---|---|---|---|---:|---:|",
    ]
    for c in convs:
        kinds = ", ".join(k for k in NUMBER_KINDS if c["note_tags"][k]) or "-"
        ov = f"{len(c['overlaps'])} (to {min(c['overlaps']):.1f} s)" if c["overlaps"] else "-"
        dur, who = c["longest"]
        variants = " + ".join(["clean"] + [v for v in VARIANT_TAGS if v in c["tags"]])
        lines.append(f"| {c['id']} | {c['my']} ⇄ {c['their']} | {spk(c)} | {c['mixed']} | {kinds} | {ov}"
                     f" | {who} {dur:.0f} s | {variants} | {c['duration']:.0f} ({c['speech']:.0f})"
                     f" | {fmt_int(c['chars'])} |")
    total = sum(c["chars"] for c in convs)
    lines.append(f"| **total** | {len(convs)} conversations | | **{sum(c['mixed'] for c in convs)}** | | "
                 f"{sum(len(c['overlaps']) for c in convs)} | | | **{sum(c['duration'] for c in convs):.0f}** "
                 f"({sum(c['speech'] for c in convs):.0f}) | **{fmt_int(total)}** |")
    by_lang = Counter()
    for c in convs:
        by_lang.update(c["chars_by_lang"])
    ref_me = sum(c["ref_chars"]["me"] for c in convs)
    ref_them = sum(c["ref_chars"]["them"] for c in convs)
    lines += [
        "",
        f"Grand total: **{fmt_int(total)}** characters of spoken text (limit {fmt_int(MAX_CHARS)}; references are"
        " not spoken and do not count).",
        "",
        "Spoken characters by the line's main language: "
        + " · ".join(f"{k} {fmt_int(v)}" for k, v in by_lang.most_common()) + ".",
        "",
        f"One interpreter run that voices every translation synthesizes about **{fmt_int(ref_me + ref_them)}**"
        f" characters (hear side {fmt_int(ref_them)}, speak side {fmt_int(ref_me)}; the reference lengths).",
    ]
    return "\n".join(lines)


def design_block(convs):
    return f"{TABLE_START}\n{table(convs)}\n{TABLE_END}"


def check_design(convs, rep, update=False):
    block = design_block(convs)
    try:
        text = DESIGN_FILE.read_text(encoding="utf-8")
    except OSError:
        rep.err("corpus/DESIGN.md is missing")
        return
    start, end = text.find(TABLE_START), text.find(TABLE_END)
    if start < 0 or end < start:
        rep.err("corpus/DESIGN.md has no generated table block (markers missing)")
        return
    current = text[start:end + len(TABLE_END)]
    if current == block:
        return
    if update:
        DESIGN_FILE.write_text(text[:start] + block + text[end + len(TABLE_END):], encoding="utf-8")
        print("corpus/DESIGN.md: table updated")
    else:
        rep.err("corpus/DESIGN.md: the table is out of date (run selftest_corpus.py --update-design)")


# ---------------------------------------------------------------- main

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--table", action="store_true", help="print the DESIGN.md table block")
    ap.add_argument("--update-design", action="store_true", help="rewrite the table block in corpus/DESIGN.md")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    rep = Report()
    voices = load_voices(rep)
    files = sorted(CONV_DIR.glob("*.json"))
    if not files:
        rep.err("corpus/conversations has no conversations")
    convs = [s for s in (check_conversation(p, voices, rep) for p in files) if s]
    if convs:
        check_coverage(convs, rep)
        check_design(convs, rep, update=args.update_design)

    for c in convs:
        print(f"{c['id']:<28} {c['my']}<->{c['their']}  {c['turns']:>2} turns  {c['chars']:>5} chars"
              f"  ~{c['speech']:>3.0f} s speech  ~{c['duration']:>3.0f} s  mixed {c['mixed']}")
    total = sum(c["chars"] for c in convs)
    print(f"total: {len(convs)} conversations, {fmt_int(total)} / {fmt_int(MAX_CHARS)} characters, "
          f"~{sum(c['duration'] for c in convs) / 60:.1f} min, {sum(c['mixed'] for c in convs)} mixed lines")
    if args.table:
        print()
        print(design_block(convs))
    for w in rep.warnings:
        print("warning:", w)
    for e in rep.errors:
        print("ERROR:", e)
    print("FAIL" if rep.errors else "OK")
    return 1 if rep.errors else 0


if __name__ == "__main__":
    sys.exit(main())
