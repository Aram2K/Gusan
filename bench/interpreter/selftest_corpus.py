# ---------------------------------------------------------------- voices

def load_voices(rep):
    try:
        data = json.loads(VOICES_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        rep.err(f"voices.json: cannot read ({e})")
        return {}
    if not isinstance(data, list):
        rep.err("voices.json: must be a list")
        return {}
    voices = {}
    for i, v in enumerate(data):
        where = f"voices.json[{i}]"
        if not isinstance(v, dict) or sorted(v) != ["gender", "id", "name", "style"]:
            rep.err(f"{where}: needs exactly the keys id, name, gender, style")
            continue
        if not all(isinstance(v[k], str) and v[k].strip() for k in v):
            rep.err(f"{where}: every field must be a non-empty string")
            continue
        if v["id"] in voices:
            rep.err(f"{where}: duplicate id {v['id']}")
        known = KNOWN_VOICES.get(v["id"])
        if not known:
            rep.err(f"{where}: {v['id']} is not one of the contract's known-good voices")
        elif (v["name"], v["gender"]) != known[:2]:
            rep.err(f"{where}: {v['id']} is {known[0]} ({known[1]}), not {v['name']} ({v['gender']})")
        voices[v["id"]] = v
    missing = set(KNOWN_VOICES) - set(voices)
    if missing:
        rep.err("voices.json: missing " + ", ".join(KNOWN_VOICES[m][0] for m in sorted(missing)))
    return voices


