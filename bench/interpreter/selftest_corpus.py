def script_of(ch):
    """The writing system of a letter (None for digits, spaces, punctuation)."""
    if not ch.isalpha():
        return None
    o = ord(ch)
    for lo, hi, name in _RANGES:
        if lo <= o <= hi:
            return name
    return "Other"


def scripts_in(text):
    return {s for s in map(script_of, text) if s}


def est_seconds(text, lang):
    return len(text) / RATES.get(lang, DEFAULT_RATE)


def note_tags(notes):
    return TAG_RE.findall(notes or "")


def fmt_int(n):
    return f"{n:,}"


