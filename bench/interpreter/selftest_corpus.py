"""Self-test for the interpreter benchmark corpus (bench/interpreter/corpus).

    python bench/interpreter/selftest_corpus.py                  check everything, print a summary
    python bench/interpreter/selftest_corpus.py --table          also print the DESIGN.md table block
    python bench/interpreter/selftest_corpus.py --update-design  rewrite that block in corpus/DESIGN.md

Exit code 1 on any error (warnings only print). Standard library only, offline. It is a script,
not a pytest file (named selftest_*, never test_*).

What it checks
  * corpus/voices.json: the 9 known-good ElevenLabs premade voices, fields id / name / gender / style.
  * Every conversation follows the shared Conversation JSON schema exactly (no missing or extra keys);
    its id matches the file name and the language pair; speakers use catalog voices of the same
    gender (no two speakers share a voice); every their-turn has ref[my_lang], every my-turn has
    ref[their_lang], every turn has ref["en"]; langs starts with lang; the letters of each line match
    its langs (Latin letters in an Armenian line need "en" in langs); gap_before is in [-0.6, 5];
    a line is at most 600 characters (the bench tts limit).
  * Notes and tags tell the truth: the #tags in notes are from a fixed list and agree with the data
    (#overlap <-> negative gap, #pause <-> gap >= 2 s, #mixed <-> more than one language, #monologue
    = 25-35 s), and the conversation tags that can be derived from the turns match them.
  * The whole corpus: <= 7,000 characters of spoken text (references are not spoken and do not
    count) and the coverage the benchmark needs (language pairs, mixed lines, gender mixes,
    overlaps, long pauses, a 25-35 s monologue, short replies, glossary terms, the speakers and
    noisy variants, formal and casual registers).
  * corpus/DESIGN.md holds exactly the table this script generates, so its numbers stay true.

Durations are estimates from characters per second per language (RATES below); generate.py
measures the real ones.
"""
